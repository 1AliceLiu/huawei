"""Two-stage training pipeline for the merged12 detector.

Stage 1: full group-disjoint training pool (train_pool.txt), strong augmentation.
Stage 2: high-quality high-density subset (train_high_quality.txt), mosaic off, low lr,
         initialised from Stage 1 best.pt.

Both stages validate against the same frozen, leak-free ``frozen_val.txt`` at imgsz=960.

    python3 scripts/run_multistage.py
    python3 scripts/run_multistage.py --smoke   # 1 epoch, 5% data

Notes / corrections vs the first draft
--------------------------------------
* base weights default to the repo's ``yolo26m.pt`` (``yolov11m.pt`` is not present and
  would trigger a download);
* ``--device`` defaults to ``-1`` = ultralytics auto-selects an idle GPU, so the busy
  physical GPU 0 is skipped automatically;
* the Stage-2 data yaml is generated programmatically instead of by string replacement.
"""
from __future__ import annotations

import argparse
import gc
import json
import time
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DS = ROOT / "dataset" / "batch_12.v14i.merged12.yolov11"
DATA_POOL_YAML = DEFAULT_DS / "splits" / "data_train_pool.yaml"
NAMES = [
    "Coach", "Franchised Bus", "HGV", "LGV", "Light Bus", "MGV",
    "Motorcycle", "PLB GMB", "Private Car", "Taxi", "Van", "Container",
]


def cleanup_memory() -> None:
    gc.collect()
    try:
        import torch

        if torch.cuda.is_available():
            torch.cuda.empty_cache()
            torch.cuda.ipc_collect()
    except Exception:
        pass


def make_hq_yaml(out: Path) -> Path:
    """Clone the pool data yaml but point ``train`` at the high-quality subset."""
    doc = yaml.safe_load(DATA_POOL_YAML.read_text(encoding="utf-8"))
    splits = DATA_POOL_YAML.parent
    doc["train"] = str(splits / "train_high_quality.txt")
    doc["val"] = str(splits / "frozen_val.txt")
    doc["test"] = str(splits / "frozen_test.txt")
    hq = out / "data_hq.yaml"
    hq.write_text(
        "# auto-generated by scripts/run_multistage.py - Stage 2 (HQ subset)\n"
        + yaml.safe_dump(doc, sort_keys=False),
        encoding="utf-8",
    )
    return hq


def metrics_dict(results) -> dict:
    def get(obj, attr):
        box = getattr(obj, "box", obj)
        return float(getattr(box, attr))

    return {
        "map50_95": get(results, "map"),
        "map50": get(results, "map50"),
        "map75": get(results, "map75"),
        "precision": float(results.box.mp),
        "recall": float(results.box.mr),
    }


def write_json(path: Path, data: dict) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    tmp.replace(path)


def run_stage(name: str, weights: str, data: str, out: Path, device: int, args, epochs: int,
              mosaic: float, mixup: float, lr0: float) -> dict:
    from ultralytics import YOLO

    print(f"\n{'=' * 60}\n>>> {name}\n{'=' * 60}", flush=True)
    model = YOLO(weights)
    results = model.train(
        data=data,
        epochs=epochs,
        imgsz=args.imgsz,
        batch=args.batch,
        project=str(args.project),
        name=out.name,
        exist_ok=True,
        optimizer=args.optimizer,
        lr0=lr0,
        lrf=args.lrf,
        momentum=args.momentum,
        weight_decay=args.weight_decay,
        mosaic=mosaic,
        mixup=mixup,
        device=device,
        workers=args.workers,
        val=True,
        plots=True,
        verbose=True,
        seed=args.seed,
        fraction=args.fraction,
    )
    best = out / "weights" / "best.pt"
    metrics = metrics_dict(results)
    metrics.update({"stage": name, "epochs": epochs, "lr0": lr0,
                    "mosaic": mosaic, "mixup": mixup, "best_weight": str(best)})
    print(f"[{name}] {metrics}", flush=True)
    del model
    cleanup_memory()
    return metrics


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base-weights", default=str(ROOT / "yolo26m.pt"))
    ap.add_argument("--project", type=Path, default=ROOT / "runs" / "experiments")
    ap.add_argument("--imgsz", type=int, default=960)
    ap.add_argument("--batch", type=int, default=16)
    ap.add_argument("--epochs1", type=int, default=150)
    ap.add_argument("--epochs2", type=int, default=50)
    ap.add_argument("--optimizer", default="SGD")
    ap.add_argument("--lr0-stage1", type=float, default=0.01)
    ap.add_argument("--lr0-stage2", type=float, default=0.001)
    ap.add_argument("--lrf", type=float, default=0.01)
    ap.add_argument("--momentum", type=float, default=0.937)
    ap.add_argument("--weight-decay", type=float, default=0.0005)
    ap.add_argument("--device", type=int, default=-1,
                    help="-1 = auto-select an idle GPU (skips busy GPUs); or an explicit cuda id")
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--smoke", action="store_true", help="1 epoch on 5%% data to validate the pipeline")
    args = ap.parse_args()

    args.project = args.project.resolve()
    args.project.mkdir(parents=True, exist_ok=True)
    if args.smoke:
        args.epochs1 = args.epochs2 = 1
        args.fraction = 0.05
        args.project = args.project / "smoke"
        args.project.mkdir(parents=True, exist_ok=True)
    else:
        args.fraction = 1.0

    import torch

    if not torch.cuda.is_available():
        raise SystemExit("CUDA not available - refusing to train on CPU at imgsz=960")
    dev_desc = "auto idle GPU" if args.device < 0 else f"cuda:{args.device} ({torch.cuda.get_device_name(args.device)})"
    print(f"base weights : {args.base_weights}")
    print(f"device       : {dev_desc}")
    print(f"imgsz/batch  : {args.imgsz}/{args.batch}   smoke={args.smoke}")

    hq_yaml = make_hq_yaml(args.project)
    start = time.time()

    s1 = run_stage("stage1_full_pool", args.base_weights, str(DATA_POOL_YAML),
                   args.project / "stage1_full_pool", args.device, args,
                   args.epochs1, mosaic=1.0, mixup=0.15, lr0=args.lr0_stage1)
    write_json(args.project / "stage1_result.json", s1)

    if not Path(s1["best_weight"]).is_file():
        raise SystemExit(f"stage1 best weight missing: {s1['best_weight']}")
    s2 = run_stage("stage2_hq_finetune", s1["best_weight"], str(hq_yaml),
                   args.project / "stage2_hq_finetune", args.device, args,
                   args.epochs2, mosaic=0.0, mixup=0.0, lr0=args.lr0_stage2)
    write_json(args.project / "stage2_result.json", s2)

    report = {
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "elapsed_hours": round((time.time() - start) / 3600, 2),
        "config": {k: str(v) for k, v in vars(args).items()},
        "stage1_results": s1,
        "stage2_results": s2,
        "delta_mAP50_95": round(s2["map50_95"] - s1["map50_95"], 4),
        "delta_mAP50": round(s2["map50"] - s1["map50"], 4),
    }
    report_path = args.project / "multistage_summary.json"
    write_json(report_path, report)

    print(f"\n{'=' * 60}")
    print(f">>> done in {report['elapsed_hours']} h")
    print(f"Stage 1 (pool) -> mAP50-95 {s1['map50_95']:.4f} | mAP50 {s1['map50']:.4f}")
    print(f"Stage 2 (HQ)   -> mAP50-95 {s2['map50_95']:.4f} | mAP50 {s2['map50']:.4f}")
    print(f"delta          -> mAP50-95 {report['delta_mAP50_95']:+.4f} | mAP50 {report['delta_mAP50']:+.4f}")
    print(f"summary        : {report_path}")
    print(f"{'=' * 60}\n")


if __name__ == "__main__":
    main()
